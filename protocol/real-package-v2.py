#!/usr/bin/env python3
"""
Protocol Harness v2 — real synthetic V12 package inside A -> c -> B -> b -> a.

Synthetic-only research harness.

A : pre-shared root locator/bootstrap codebook
a : synthetic payload generated by the V12 engine
b : published numeric NPZ package bytes
B : per-package V12 manifest JSON
c : fingerprint-bearing outer package containing B + b + integrity
d : synthetic background records

Receiver:
    A -> locate c -> verify/open c -> extract B+b -> V12 decoder -> recover a
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import hmac
import io
import json
import math
import runpy
import tempfile
from dataclasses import dataclass
from pathlib import Path

import numpy as np


@dataclass(frozen=True)
class RootCodebookA:
    version: str
    root_key_hex: str
    fingerprint_length: int
    fingerprint_alphabet: int
    field_manifest: str
    field_payload: str
    field_tag: str
    manifest_format: str
    payload_format: str

    @property
    def root_key(self):
        return bytes.fromhex(self.root_key_hex)

    def expected_fingerprint(self):
        out = {}
        for i in range(self.fingerprint_length):
            digest = hmac.new(
                self.root_key,
                f"locator-slot-{i}".encode(),
                hashlib.sha256,
            ).digest()
            out[f"slot_{i:02d}"] = (
                int.from_bytes(digest[:4], "big")
                % self.fingerprint_alphabet
            )
        return out


def default_A():
    return RootCodebookA(
        version="A-v2",
        root_key_hex=hashlib.sha256(
            b"synthetic-root-A-v2"
        ).hexdigest(),
        fingerprint_length=32,
        fingerprint_alphabet=192,
        field_manifest="m",
        field_payload="p",
        field_tag="t",
        manifest_format="json-v12-manifest",
        payload_format="npz-v12-published-package",
    )


def load_engine(engine_path: Path):
    ns = runpy.run_path(str(engine_path))
    required = [
        "run_package",
        "decode_table",
        "bits_to_bytes",
    ]
    missing = [k for k in required if k not in ns]
    if missing:
        raise RuntimeError(f"engine missing: {missing}")
    return ns


def generate_real_B_b(engine, payload_bytes: int, channels: int):
    with tempfile.TemporaryDirectory() as td:
        out = Path(td)
        result = engine["run_package"](
            payload_bytes=payload_bytes,
            channels=channels,
            out_dir=out,
        )
        manifest_path = (
            out / "manifest_adaptive_q_v12.json"
        )
        package_path = (
            out / "published_adaptive_q_v12.npz"
        )
        B_bytes = manifest_path.read_bytes()
        b_bytes = package_path.read_bytes()
        B = json.loads(B_bytes.decode("utf-8"))

    return B, B_bytes, b_bytes, result


def package_tag(A: RootCodebookA, B_bytes: bytes, b_bytes: bytes):
    return hmac.new(
        A.root_key,
        b"c-v2|" + B_bytes + b"|" + b_bytes,
        hashlib.sha256,
    ).hexdigest()


def make_c(
    A,
    B_bytes,
    b_bytes,
    rng,
    erase_rate=0.25,
    substitute_rate=0.10,
):
    fp = A.expected_fingerprint().copy()
    for label in list(fp):
        if rng.random() < erase_rate:
            del fp[label]
        elif rng.random() < substitute_rate:
            old = fp[label]
            v = int(rng.integers(0, A.fingerprint_alphabet - 1))
            if v >= old:
                v += 1
            fp[label] = v

    return {
        "record_type": "synthetic-candidate-package",
        "structure": fp,
        A.field_manifest: base64.b64encode(B_bytes).decode(),
        A.field_payload: base64.b64encode(b_bytes).decode(),
        A.field_tag: package_tag(A, B_bytes, b_bytes),
    }


def make_d(A, rng, near=False, share_fraction=0.50):
    expected = A.expected_fingerprint()
    structure = {
        label: int(rng.integers(0, A.fingerprint_alphabet))
        for label in expected
    }
    if near:
        labels = list(expected)
        k = int(round(share_fraction * len(labels)))
        chosen = rng.choice(labels, size=k, replace=False)
        for label in chosen:
            structure[str(label)] = expected[str(label)]

    fake_m = rng.bytes(128)
    fake_p = rng.bytes(1024)
    fake_t = hashlib.sha256(rng.bytes(48)).hexdigest()

    return {
        "record_type": "synthetic-background-record",
        "structure": structure,
        A.field_manifest: base64.b64encode(fake_m).decode(),
        A.field_payload: base64.b64encode(fake_p).decode(),
        A.field_tag: fake_t,
    }


def locator_score(A, record):
    expected = A.expected_fingerprint()
    observed = record.get("structure", {})
    common = [k for k in expected if k in observed]
    if not common:
        return 0.0
    matches = sum(
        observed[k] == expected[k]
        for k in common
    )
    coverage = len(common) / len(expected)
    return (matches / len(common)) * math.sqrt(coverage)


def rank_candidates(A, corpus):
    scores = [locator_score(A, x) for x in corpus]
    order = np.argsort(
        -np.asarray(scores),
        kind="stable",
    )
    return [
        {
            "index": int(i),
            "score": float(scores[i]),
        }
        for i in order
    ]


def decode_v12_from_B_b(engine, B_bytes: bytes, b_bytes: bytes):
    B = json.loads(B_bytes.decode("utf-8"))
    loaded = np.load(io.BytesIO(b_bytes))

    recovered_bits = np.zeros(
        int(B["payload_bit_length"]),
        dtype=np.uint8,
    )

    for table in B["tables"]:
        tid = int(table["table_id"])
        bits = engine["decode_table"](
            loaded[f"table_{tid}_y"],
            table,
        )
        offset = int(table["payload_bit_offset"])
        recovered_bits[
            offset:offset + len(bits)
        ] = bits

    recovered = engine["bits_to_bytes"](
        recovered_bits
    )[: int(B["payload_bytes"])]

    sha = hashlib.sha256(recovered).hexdigest()
    return {
        "payload": recovered,
        "payload_sha256": sha,
        "manifest_payload_sha256": B["payload_sha256"],
        "exact_sha_match": sha == B["payload_sha256"],
        "B": B,
    }


def try_open(A, engine, record):
    try:
        B_bytes = base64.b64decode(
            record[A.field_manifest],
            validate=True,
        )
        b_bytes = base64.b64decode(
            record[A.field_payload],
            validate=True,
        )
        tag = str(record[A.field_tag])
    except Exception:
        return {
            "accepted": False,
            "reason": "A_bootstrap_parse_failed",
        }

    expected_tag = package_tag(
        A,
        B_bytes,
        b_bytes,
    )
    if not hmac.compare_digest(tag, expected_tag):
        return {
            "accepted": False,
            "reason": "c_outer_integrity_failed",
        }

    try:
        decoded = decode_v12_from_B_b(
            engine,
            B_bytes,
            b_bytes,
        )
    except Exception as exc:
        return {
            "accepted": False,
            "reason": "B_or_b_decode_failed",
            "detail": type(exc).__name__,
        }

    if not decoded["exact_sha_match"]:
        return {
            "accepted": False,
            "reason": "a_final_verification_failed",
        }

    return {
        "accepted": True,
        "reason": "strict_verify_pass",
        **decoded,
    }


def receive(A, engine, corpus, top_k):
    ranked = rank_candidates(A, corpus)
    attempts = []

    for rank, item in enumerate(ranked[:top_k], start=1):
        opened = try_open(
            A,
            engine,
            corpus[item["index"]],
        )
        attempts.append({
            "rank": rank,
            "index": item["index"],
            "locator_score": item["score"],
            "accepted": opened["accepted"],
            "reason": opened["reason"],
        })
        if opened["accepted"]:
            return {
                "accepted": True,
                "rank": rank,
                "index": item["index"],
                "locator_score": item["score"],
                "attempts": attempts,
                "payload": opened["payload"],
                "payload_sha256": opened["payload_sha256"],
                "B": opened["B"],
            }

    return {
        "accepted": False,
        "attempts": attempts,
    }


def run_once(
    engine_path,
    payload_bytes,
    channels,
    corpus_size,
    near_decoy_fraction,
    erase_rate,
    substitute_rate,
    top_k,
    seed,
):
    engine = load_engine(engine_path)
    A = default_A()
    rng = np.random.default_rng(seed)

    B, B_bytes, b_bytes, engine_result = generate_real_B_b(
        engine,
        payload_bytes,
        channels,
    )
    a_sha = B["payload_sha256"]

    c = make_c(
        A,
        B_bytes,
        b_bytes,
        rng,
        erase_rate=erase_rate,
        substitute_rate=substitute_rate,
    )

    target_idx = int(rng.integers(0, corpus_size))
    near_count = min(
        corpus_size - 1,
        int(round(
            near_decoy_fraction * (corpus_size - 1)
        )),
    )
    pool = np.asarray(
        [i for i in range(corpus_size) if i != target_idx],
        dtype=int,
    )
    near_ids = set(
        int(x) for x in rng.choice(
            pool,
            size=near_count,
            replace=False,
        )
    )

    corpus = []
    for i in range(corpus_size):
        if i == target_idx:
            corpus.append(c)
        else:
            corpus.append(
                make_d(
                    A,
                    rng,
                    near=i in near_ids,
                )
            )

    ranked = rank_candidates(A, corpus)
    target_rank = next(
        r + 1
        for r, row in enumerate(ranked)
        if row["index"] == target_idx
    )

    received = receive(
        A,
        engine,
        corpus,
        top_k=top_k,
    )

    exact = bool(
        received.get("accepted")
        and received.get("payload_sha256") == a_sha
    )

    return {
        "scope": "synthetic-only real-package protocol harness",
        "protocol_chain": "A -> c -> B -> b -> a",
        "objects": {
            "A": {
                "version": A.version,
                "fingerprint_length": A.fingerprint_length,
                "fingerprint_alphabet": A.fingerprint_alphabet,
                "manifest_format": A.manifest_format,
                "payload_format": A.payload_format,
            },
            "a": {
                "payload_bytes": int(B["payload_bytes"]),
                "sha256": a_sha,
            },
            "B": {
                "manifest_bytes": len(B_bytes),
                "tables": len(B["tables"]),
                "q_schedule": [
                    int(t["q"]) for t in B["tables"]
                ],
            },
            "b": {
                "published_npz_bytes": len(b_bytes),
            },
            "c": {
                "target_index": target_idx,
                "observed_fingerprint_positions":
                    len(c["structure"]),
            },
            "d": {
                "background_records": corpus_size - 1,
                "near_decoys": len(near_ids),
            },
        },
        "locator": {
            "target_rank": target_rank,
            "top_k": top_k,
            "accepted_rank": received.get("rank"),
            "attempt_count": len(
                received.get("attempts", [])
            ),
        },
        "recovery": {
            "accepted": bool(received.get("accepted")),
            "exact_a_recovery": exact,
            "recovered_sha256":
                received.get("payload_sha256"),
        },
        "engine_summary": {
            "published_rows_total":
                engine_result.get("published_rows_total"),
            "gross_bits_per_numeric_value":
                engine_result.get("gross_bits_per_numeric_value"),
            "q_distribution":
                engine_result.get("q_distribution"),
        },
        "attempts": received.get("attempts", []),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", type=Path, required=True)
    ap.add_argument("--payload-bytes", type=int, default=2048)
    ap.add_argument("--channels", type=int, default=4)
    ap.add_argument("--corpus-size", type=int, default=3000)
    ap.add_argument("--near-decoy-fraction", type=float, default=0.01)
    ap.add_argument("--erase-rate", type=float, default=0.25)
    ap.add_argument("--substitute-rate", type=float, default=0.10)
    ap.add_argument("--top-k", type=int, default=100)
    ap.add_argument("--seed", type=int, default=20261102)
    ap.add_argument(
        "--out",
        type=Path,
        default=Path("protocol_real_package_v2_result.json"),
    )
    args = ap.parse_args()

    result = run_once(
        args.engine,
        args.payload_bytes,
        args.channels,
        args.corpus_size,
        args.near_decoy_fraction,
        args.erase_rate,
        args.substitute_rate,
        args.top_k,
        args.seed,
    )

    args.out.write_text(
        json.dumps(result, indent=2),
        encoding="utf-8",
    )

    print("target_rank:", result["locator"]["target_rank"])
    print("accepted_rank:", result["locator"]["accepted_rank"])
    print("attempt_count:", result["locator"]["attempt_count"])
    print("exact_a_recovery:", result["recovery"]["exact_a_recovery"])

    if not result["recovery"]["exact_a_recovery"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
